// Generate the constants block embedded in seed-console.js from schema.json.
// The console script stays a single pasteable file with no imports; only the
// marked constants region is rewritten, so the parser and the user's data are
// never touched.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "src/core/schema.json");
const consolePath = resolve(root, "seed-console.js");

const START = "// -- generated schema constants (start) --";
const END = "// -- generated schema constants (end) --";

const schema = JSON.parse(await readFile(schemaPath, "utf8"));

const asRecord = (values) => Object.fromEntries(values.map((value) => [value, value]));
// Match oxfmt: identifier-safe keys are emitted unquoted so regeneration is a
// no-op after formatting and the CI drift guard stays meaningful.
const keyLiteral = (key) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key));
const frozenRecord = (values, indent) => {
  const entries = Object.keys(asRecord(values)).map(
    (key) => `${indent}    ${keyLiteral(key)}: ${JSON.stringify(key)},`,
  );
  return ["Object.freeze({", ...entries, `${indent}  })`].join("\n");
};

const block = [
  START,
  "  // Generated by `npm run schema:codegen` from src/core/schema.json. Do not edit.",
  "  const SCHEMA = Object.freeze({",
  `    cnyToByn: ${schema.cnyToByn},`,
  `    selfCustomerName: ${JSON.stringify(schema.selfCustomerName)},`,
  `    parcelStatus: ${frozenRecord(schema.parcelStatuses, "  ")},`,
  `    itemStatus: ${frozenRecord(schema.itemStatuses, "  ")},`,
  `    unit: ${frozenRecord(schema.units, "  ")},`,
  `    paymentType: ${frozenRecord(schema.paymentTypes, "  ")},`,
  `    table: ${frozenRecord(schema.tables, "  ")},`,
  `    jsonField: ${frozenRecord(schema.jsonFields, "  ")},`,
  "  });",
  "  " + END,
].join("\n");

const source = await readFile(consolePath, "utf8");
const startIndex = source.indexOf(START);
const endIndex = source.indexOf(END);
if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
  throw new Error("seed-console.js: не найдены маркеры сгенерированных констант");
}

const next = source.slice(0, startIndex) + block + source.slice(endIndex + END.length);
await writeFile(consolePath, next);
console.log("seed-console.js: сгенерированные константы обновлены из schema.json");
