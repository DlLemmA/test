-- Cloud-first schema for «Учёт посылок».
-- Supabase Postgres is the single source of truth; both users share one workspace.

create table public.workspace_members (
  user_id uuid primary key references auth.users (id) on delete cascade,
  email text not null unique
);

-- SECURITY DEFINER avoids recursive RLS checks on workspace_members.
create or replace function public.is_workspace_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.workspace_members where user_id = auth.uid()
  );
$$;

revoke all on function public.is_workspace_member() from public;
grant execute on function public.is_workspace_member() to authenticated;

-- ---------------------------------------------------------------------------
-- Domain tables
