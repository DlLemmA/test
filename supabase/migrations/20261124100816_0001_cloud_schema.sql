-- New parcel + its items in one transaction.
create or replace function public.create_parcel_with_items(
  p_parcel jsonb,
  p_items jsonb[] default '{}'::jsonb[]
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_parcel_id bigint;
  v_item jsonb;
begin
  insert into public.parcels (
    name, status, comment, box_weight_g, shipping_cost_byn,
    shipped_at, received_at, completed_at, created_at
  )
  values (
    nullif(p_parcel ->> 'name', ''),
    coalesce(p_parcel ->> 'status', 'draft'),
    nullif(p_parcel ->> 'comment', ''),
    nullif(p_parcel ->> 'boxWeightG', '')::integer,
    nullif(p_parcel ->> 'shippingCostBYN', '')::numeric,
    nullif(p_parcel ->> 'shippedAt', '')::timestamptz,
    nullif(p_parcel ->> 'receivedAt', '')::timestamptz,
    nullif(p_parcel ->> 'completedAt', '')::timestamptz,
    coalesce(nullif(p_parcel ->> 'createdAt', '')::timestamptz, now())
  )
  returning id into v_parcel_id;

  foreach v_item in array p_items loop
    insert into public.parcel_items (
      parcel_id, name, price_cny, price_byn, quantity, unit,
      customer_id, track_numbers, weights_g, status,
      tracks_completed_at, created_at
    )
    values (
      v_parcel_id,
      v_item ->> 'name',
      (v_item ->> 'priceCNY')::numeric,
      (v_item ->> 'priceBYN')::numeric,
      coalesce((v_item ->> 'quantity')::integer, 1),
      coalesce(v_item ->> 'unit', 'pcs'),
      (v_item ->> 'customerId')::bigint,
      coalesce(v_item ->> 'trackNumbers', '[]'),
      coalesce(v_item ->> 'weightsG', '[]'),
      coalesce(v_item ->> 'status', 'ordered'),
      nullif(v_item ->> 'tracksCompletedAt', '')::timestamptz,
      coalesce(nullif(v_item ->> 'createdAt', '')::timestamptz, now())
    );
  end loop;

  return v_parcel_id;
end;
$$;

-- Atomic full replacement for demo seed / test fixtures.
create or replace function public.replace_workspace(p_snapshot jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  delete from public.payments;
  delete from public.parcel_items;
  delete from public.parcels;
  delete from public.customers;

  insert into public.customers (id, name, is_self)
  select (r ->> 'id')::bigint, r ->> 'name', coalesce((r ->> 'isSelf')::boolean, false)
  from jsonb_array_elements(p_snapshot -> 'customers') as r;

  insert into public.parcels (
    id, name, status, comment, box_weight_g, shipping_cost_byn,
    shipped_at, received_at, completed_at, created_at
  )
  select
    (r ->> 'id')::bigint,
    nullif(r ->> 'name', ''),
    coalesce(r ->> 'status', 'draft'),
    nullif(r ->> 'comment', ''),
    nullif(r ->> 'boxWeightG', '')::integer,
    nullif(r ->> 'shippingCostBYN', '')::numeric,
    nullif(r ->> 'shippedAt', '')::timestamptz,
    nullif(r ->> 'receivedAt', '')::timestamptz,
    nullif(r ->> 'completedAt', '')::timestamptz,
    coalesce(nullif(r ->> 'createdAt', '')::timestamptz, now())
  from jsonb_array_elements(p_snapshot -> 'parcels') as r;

  insert into public.parcel_items (
    id, parcel_id, name, price_cny, price_byn, quantity, unit,
    customer_id, track_numbers, weights_g, status,
    tracks_completed_at, created_at
  )
  select
    (r ->> 'id')::bigint,
    (r ->> 'parcelId')::bigint,
    r ->> 'name',
    (r ->> 'priceCNY')::numeric,
    (r ->> 'priceBYN')::numeric,
    coalesce((r ->> 'quantity')::integer, 1),
    coalesce(r ->> 'unit', 'pcs'),
    (r ->> 'customerId')::bigint,
    coalesce(r ->> 'trackNumbers', '[]'),
    coalesce(r ->> 'weightsG', '[]'),
    coalesce(r ->> 'status', 'ordered'),
    nullif(r ->> 'tracksCompletedAt', '')::timestamptz,
    coalesce(nullif(r ->> 'createdAt', '')::timestamptz, now())
  from jsonb_array_elements(p_snapshot -> 'parcelItems') as r;

  insert into public.payments (
    id, parcel_id, customer_id, item_id, type, paid, paid_at, created_at
  )
  select
    (r ->> 'id')::bigint,
    (r ->> 'parcelId')::bigint,
    (r ->> 'customerId')::bigint,
    nullif(r ->> 'itemId', '')::bigint,
    r ->> 'type',
    coalesce((r ->> 'paid')::boolean, false),
    nullif(r ->> 'paidAt', '')::timestamptz,
    coalesce(nullif(r ->> 'createdAt', '')::timestamptz, now())
  from jsonb_array_elements(p_snapshot -> 'payments') as r;

  -- Keep identity sequences ahead of explicitly imported ids.
  perform setval(
    pg_get_serial_sequence('public.customers', 'id'),
    greatest(coalesce((select max(id) from public.customers), 1), 1),
    exists (select 1 from public.customers)
  );
  perform setval(
    pg_get_serial_sequence('public.parcels', 'id'),
    greatest(coalesce((select max(id) from public.parcels), 1), 1),
    exists (select 1 from public.parcels)
  );
  perform setval(
    pg_get_serial_sequence('public.parcel_items', 'id'),
    greatest(coalesce((select max(id) from public.parcel_items), 1), 1),
    exists (select 1 from public.parcel_items)
  );
  perform setval(
    pg_get_serial_sequence('public.payments', 'id'),
    greatest(coalesce((select max(id) from public.payments), 1), 1),
    exists (select 1 from public.payments)
  );
end;
$$;

revoke all on function public.create_parcel_with_items(jsonb, jsonb[]) from public;
revoke all on function public.replace_workspace(jsonb) from public;
grant execute on function public.create_parcel_with_items(jsonb, jsonb[]) to authenticated;
grant execute on function public.replace_workspace(jsonb) to authenticated;
