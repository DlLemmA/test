create table public.customers (
  workspace_id text not null default 'family',
  id bigint generated by default as identity primary key,
  name text not null,
  is_self boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (workspace_id, id)
);

create table public.parcels (
  workspace_id text not null default 'family',
  id bigint generated by default as identity primary key,
  name text,
  status text not null default 'draft'
    check (status in ('draft', 'shipped', 'received', 'done')),
  comment text,
  box_weight_g integer,
  shipping_cost_byn numeric(12, 2),
  shipped_at timestamptz,
  received_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, id)
);

create table public.parcel_items (
  workspace_id text not null default 'family',
  id bigint generated by default as identity primary key,
  parcel_id bigint not null,
  name text not null,
  price_cny numeric(12, 2) not null,
  price_byn numeric(12, 2) not null,
  quantity integer not null default 1,
  unit text not null default 'pcs' check (unit in ('pcs', 'packs', 'pairs')),
  customer_id bigint not null,
  track_numbers text not null default '[]',
  weights_g text not null default '[]',
  status text not null default 'ordered'
    check (status in ('ordered', 'shipped', 'received', 'lost')),
  tracks_completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, id),
  foreign key (workspace_id, parcel_id)
    references public.parcels (workspace_id, id) on delete cascade,
  foreign key (workspace_id, customer_id)
    references public.customers (workspace_id, id)
);

create table public.payments (
  workspace_id text not null default 'family',
  id bigint generated by default as identity primary key,
  parcel_id bigint not null,
  customer_id bigint not null,
  item_id bigint,
  type text not null check (type in ('item', 'shipping')),
  paid boolean not null default false,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, id),
  foreign key (workspace_id, parcel_id)
    references public.parcels (workspace_id, id) on delete cascade,
  foreign key (workspace_id, customer_id)
    references public.customers (workspace_id, id),
  foreign key (workspace_id, item_id)
    references public.parcel_items (workspace_id, id) on delete cascade
);

-- ---------------------------------------------------------------------------
-- updated_at maintenance
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger customers_set_updated_at
  before update on public.customers
  for each row execute function public.set_updated_at();

create trigger parcels_set_updated_at
  before update on public.parcels
  for each row execute function public.set_updated_at();

create trigger parcel_items_set_updated_at
  before update on public.parcel_items
  for each row execute function public.set_updated_at();

create trigger payments_set_updated_at
  before update on public.payments
  for each row execute function public.set_updated_at();

